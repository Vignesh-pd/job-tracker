import type { ReactNode } from 'react'
import { Button, Modal } from './ui'
import { MarkdownView } from './MarkdownView'
import { Copy, Download, Printer } from 'lucide-react'
import { copyText, downloadBlob } from '../lib/utils'
import { useStore } from '../store'
import type { AppDoc } from '../lib/types'
/**
 * Opens a print-window containing the document (browser "Save as PDF") and
 * also shows it inside a modal so it can be copied / downloaded.
 */
export function printDoc(content: string) {
  const w = window.open('', '_blank', 'width=880,height=1000')
  if (!w) return
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const fmt = (s: string) =>
    esc(s)
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, '$1')
  let body = ''
  let inList = false
  for (const line of content.split('\n')) {
    if (line.trim() === '') {
      if (inList) {
        body += '</ul>'
        inList = false
      }
      continue
    }
    const h = line.match(/^(#{1,4})\s+(.*)$/)
    const b = line.match(/^\s*(?:[-*•·]|\d+[.)])\s+(.*)$/)
    if (h) {
      if (inList) {
        body += '</ul>'
        inList = false
      }
      const l = h[1].length
      body += `<h${l + 1}>${fmt(h[2])}</h${l + 1}>`
    } else if (b) {
      if (!inList) {
        body += '<ul>'
        inList = true
      }
      body += `<li>${fmt(b[1])}</li>`
    } else {
      if (inList) {
        body += '</ul>'
        inList = false
      }
      body += `<p>${fmt(line)}</p>`
    }
  }
  if (inList) body += '</ul>'
  w.document.write(
    `<!doctype html><html><head><meta charset="utf-8"><title>Document</title>
    <style>
      body { font-family: 'Segoe UI', Arial, sans-serif; font-size: 13px; line-height: 1.55; color: #111; max-width: 700px; margin: 40px auto; padding: 0 24px; }
      h1, h2 { border-bottom: 1px solid #ddd; padding-bottom: 4px; }
      h3 { margin-top: 18px; }
      li { margin: 2px 0 2px -16px; }
      p { margin: 8px 0; }
    </style></head><body>${body}</body></html>`,
  )
  w.document.close()
  setTimeout(() => w.print(), 400)
}

function docFileSlug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') || 'document'
}

export function DocumentPreviewModal({ doc, onClose }: { doc: AppDoc | null; onClose: () => void }) {
  const { toast, deleteDocument } = useStore()
  if (!doc) return null
  return (
    <Modal open={!!doc} onClose={onClose} title={<span className="truncate">{doc.title} <span className="badge-version text-ink-400 font-medium">· v{doc.version}</span></span>} wide>
      <div className="space-y-3">
        <div className="flex flex-wrap items-center justify-between gap-2 rounded-xl bg-ink-50 dark:bg-ink-800/50 border border-ink-200 dark:border-ink-800 px-3 py-2">
          <p className="text-[11px] text-ink-500 dark:text-ink-300">
            Generated by <span className="font-semibold text-brand-600 dark:text-brand-400">{doc.provider}{doc.model ? ` · ${doc.model.replace(/^models\//, '')}` : ''}</span>
          </p>
          <div className="flex items-center gap-1">
            <Button variant="ghost" size="xs" onClick={() => copyText(doc.content).then(() => toast('success', 'Copied to clipboard'))}>
              <Copy className="size-3.5" /> Copy
            </Button>
            <Button variant="ghost" size="xs" onClick={() => downloadBlob(doc.content, `${docFileSlug(doc.title)}-v${doc.version}.md`, 'text/markdown')}>
              <Download className="size-3.5" /> .md
            </Button>
            <Button variant="ghost" size="xs" onClick={() => printDoc(doc.content)}>
              <Printer className="size-3.5" /> PDF
            </Button>
            <Button variant="ghost" size="xs" className="text-rose-500 hover:text-rose-600" onClick={() => { deleteDocument(doc.id!).then(onClose); toast('info', 'Document deleted') }}>
              Delete
            </Button>
          </div>
        </div>
        <PrintableArea>
          <MarkdownView content={doc.content} />
        </PrintableArea>
      </div>
    </Modal>
  )
}

function PrintableArea({ children }: { children: ReactNode }) {
  return (
    <div className="print-area relative rounded-2xl border border-ink-200 dark:border-ink-800 bg-white dark:bg-ink-900 p-5">
      {children}
    </div>
  )
}

